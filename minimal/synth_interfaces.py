#!/usr/bin/env python3
"""synth_interfaces.py — minimal-import interface synthesis from microgokujo TSV.

Input:  deps TSV produced by `microgokujo deps <Module>...`:
            <module>\t<constant>\t<kind>\t<used_const,used_const,...>
Output: per-declaration interface files with *minimal import sets* —
        the modules of the declaration's transitive constant closure,
        instead of `import Mathlib`.

Usage:
    synth_interfaces.py deps.tsv --decl Mathlib.Data.Nat.Basic.someTheorem
    synth_interfaces.py deps.tsv --module Mathlib.Data.Nat.Basic --out ifaces/
    synth_interfaces.py deps.tsv --stats

The transitive closure is computed over the *used-constant graph*
(type + value).  Module membership of used constants comes from the same
TSV (constants not defined in the TSV's module set are external anchors:
their modules must be supplied by a wider `deps` run, e.g. all of Mathlib).
"""
import argparse
import os
import sys
from collections import defaultdict


def load_deps(path):
    const_mod = {}      # constant -> defining module
    used = {}           # constant -> [used constants]
    with open(path, encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 4:
                continue
            mod, name, _kind, useds = parts[0], parts[1], parts[2], parts[3]
            const_mod[name] = mod
            used[name] = [u for u in useds.split(",") if u] if useds else []
    return const_mod, used


def unresolved(root, const_mod, used):
    """Closure constants that have no defining module in the TSV and are not
    toolchain-implicit. Non-empty on a partial TSV — callers should treat
    the resulting interface as incomplete rather than silently correct."""
    clos = closure(root, used)
    return sorted(c for c in clos
                  if c not in const_mod and not c.startswith(("Init.", "Lean.", "Std.")))


def closure(root, used):
    seen, stack = set(), [root]
    while stack:
        c = stack.pop()
        for u in used.get(c, []):
            if u not in seen:
                seen.add(u)
                stack.append(u)
    seen.discard(root)
    return seen


def minimal_imports(root, const_mod, used):
    mods = {const_mod[c] for c in closure(root, used) if c in const_mod}
    mods.discard(const_mod.get(root))
    return sorted(mods)


def render_iface(root, const_mod, used):
    mods = minimal_imports(root, const_mod, used)
    lines = [f"/- Interface for `{root}` — auto-generated by synth_interfaces.py",
             f"   closure: {len(closure(root, used))} constants, "
             f"{len(mods)} imports (was: `import Mathlib`). -/"]
    missing = unresolved(root, const_mod, used)
    if missing:
        lines.append(f"/-! WARNING: {len(missing)} closure constants unresolved in this TSV "
                     "(partial dump — regenerate against a full deps TSV): "
                     + ", ".join(missing[:20])
                     + (" …" if len(missing) > 20 else "") + " -/")
    lines += [f"import {m}" for m in mods]
    return "\n".join(lines) + "\n"


def safe_iface_path(out_dir, root):
    """Map a declaration name to a path strictly inside out_dir."""
    rel = root.replace(".", "/") + ".lean"
    dest = os.path.realpath(os.path.join(out_dir, rel))
    base = os.path.realpath(out_dir)
    if not (dest == base or dest.startswith(base + os.sep)):
        raise ValueError(f"declaration name escapes --out directory: {root!r}")
    return dest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("deps")
    ap.add_argument("--decl")
    ap.add_argument("--module")
    ap.add_argument("--out", default="ifaces")
    ap.add_argument("--stats", action="store_true")
    a = ap.parse_args()

    const_mod, used = load_deps(a.deps)
    if a.stats:
        mods = defaultdict(int)
        for m in const_mod.values():
            mods[m] += 1
        print(f"constants={len(const_mod)} modules={len(mods)}")
        for m, n in sorted(mods.items(), key=lambda t: -t[1])[:20]:
            print(f"  {n:6d}  {m}")
        return

    if a.decl:
        sys.stdout.write(render_iface(a.decl, const_mod, used))
        return

    if a.module:
        os.makedirs(a.out, exist_ok=True)
        roots = [c for c, m in const_mod.items() if m == a.module]
        for r in roots:
            path = safe_iface_path(a.out, r)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as f:
                f.write(render_iface(r, const_mod, used))
        print(f"wrote {len(roots)} interface files under {a.out}")
        return

    ap.error("need --decl, --module, or --stats")


if __name__ == "__main__":
    main()
